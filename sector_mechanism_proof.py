@dataclass
class MechanismProof:
    """
    Complete proof of the mechanism theorem.
    
    Attributes
    ----------
    mechanism_candidate : MechanismTheoremCandidate
        The theorem being proved.
    
    proof_strategy : ProofStrategy
        The strategy used (acyclic homotopy, generation, recurrence, or SS).
    
    proof_text : str
        The complete proof.
    
    validation_report : Dict
        Proof validation results.
    
    validation_status : str
        "Valid", "Incomplete", "Needs Revision"
    """
    mechanism_candidate: MechanismTheoremCandidate
    proof_strategy: ProofStrategy
    proof_text: str = ""
    validation_report: Dict[str, Any] = field(default_factory=dict)
    validation_status: str = "Not validated"


class MechanismProver:
    """
    Orchestrates proof construction and validation.
    
    Attributes
    ----------
    mechanism_candidate : MechanismTheoremCandidate
        The mechanism to prove.
    
    proof : optional MechanismProof
        The constructed proof.
    
    proof_strategy : optional ProofStrategy
        The selected proof strategy.
    """
    
    def __init__(self, mechanism_candidate: MechanismTheoremCandidate):
        self.mechanism_candidate = mechanism_candidate
        self.proof: Optional[MechanismProof] = None
        self.proof_strategy: Optional[ProofStrategy] = None
    
    def select_proof_strategy(self) -> ProofStrategy:
        """Select and construct appropriate proof strategy."""
        mechanism_type = self.mechanism_candidate.mechanism_type
        
        if mechanism_type == MechanismType.ACYCLIC_TAIL:
            # Extract candidate-specific type
            candidate = self.mechanism_candidate
            acyclic_candidate = AcyclicTailCandidiate(
                cochain_level=candidate.cochain_level,
                support_threshold=candidate.exact_labels.get('support_threshold', {}),
                acyclic_regions=[],
                nonzero_regions=[],
                threshold_confidence=candidate.confidence,
                evidence_sectors=candidate.evidence.get('sectors_analyzed', 0),
                proof_status="Conjectured",
                gaps=[],
            )
            self.proof_strategy = ContractingHomotopyProof(acyclic_candidate)
        
        elif mechanism_type == MechanismType.FINITE_GENERATION:
            candidate = self.mechanism_candidate
            generation_candidate = FiniteGenerationCandidate(
                cochain_level=candidate.cochain_level,
                generators=candidate.exact_labels.get('generators', []),
                generation_rule=candidate.exact_labels.get('generation_rule', ''),
                character_formula=candidate.exact_labels.get('character_formula', ''),
                evidence_sectors=candidate.evidence.get('sectors_analyzed', 0),
                generation_confidence=candidate.confidence,
                proof_status="Conjectured",
                gaps=[],
            )
            self.proof_strategy = GenerationTheoremProof(generation_candidate)
        
        elif mechanism_type == MechanismType.PERIODICITY_RECURRENCE:
            candidate = self.mechanism_candidate
            periodicity_candidate = PeriodicityCandidate(
                cochain_level=candidate.cochain_level,
                shift_rule=candidate.exact_labels.get('shift_rule', ''),
                period=candidate.exact_labels.get('period', None),
                evidence_sectors=candidate.evidence.get('sectors_analyzed', 0),
                periodicity_confidence=candidate.confidence,
                proof_status="Conjectured",
                gaps=[],
            )
            self.proof_strategy = RecurrenceProof(periodicity_candidate)
        
        elif mechanism_type == MechanismType.SPECTRAL_SEQUENCE:
            candidate = self.mechanism_candidate
            spectral_candidate = SpectralSequenceCandidate(
                cochain_level=candidate.cochain_level,
                filtration=candidate.exact_labels.get('filtration', ''),
                vanishing_threshold=candidate.exact_labels.get('vanishing_threshold', {}),
                evidence_sectors=candidate.evidence.get('sectors_analyzed', 0),
                exactness_confidence=candidate.confidence,
                proof_status="Conjectured",
                gaps=[],
            )
            self.proof_strategy = SpectralSequenceProof(spectral_candidate)
        
        return self.proof_strategy
    
    def prove_mechanism(self) -> MechanismProof:
        """Construct and validate the proof."""
        # Select strategy
        strategy = self.select_proof_strategy()
        
        # Construct proof
        proof_text = strategy.construct_proof()
        
        # Validate
        validator = ProofValidator(strategy)
        validation_report = validator.validate()
        
        # Create proof object
        validation_status = "Valid" if validation_report.get('coverage_complete') else "Incomplete"
        
        self.proof = MechanismProof(
            mechanism_candidate=self.mechanism_candidate,
            proof_strategy=strategy,
            proof_text=proof_text,
            validation_report=validation_report,
            validation_status=validation_status,
        )
        
        return self.proof
    
    def proof_report(self) -> str:
        """Generate complete proof report."""
        if not self.proof:
            return "No proof constructed yet."
        
        lines = [
            "=" * 80,
            "MECHANISM PROOF REPORT",
            "=" * 80,
            f"\nMechanism: {self.mechanism_candidate.mechanism_type.value}",
            f"Cochain Level: H^{self.mechanism_candidate.cochain_level}",
            f"Proof Status: {self.proof.validation_status}",
            "",
            self.proof.proof_text,
            "",
            "=" * 80,
            "VALIDATION",
            "=" * 80,
            "",
        ]
        
        validator = ProofValidator(self.proof.proof_strategy)
        validator.validation_report = self.proof.validation_report
        lines.append(validator.validation_report_text())
        
        return "\n".join(lines)


