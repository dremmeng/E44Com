class ProofValidator:
    """
    Validates proof completeness and rigor.
    
    Checks that the proof covers:
      1. All PBW degrees (computed and omitted)
      2. All cochain t levels
      3. All sl₄ weight arms
      4. Explains non-occurrence of cohomology outside core (or generation)
    """
    
    def __init__(self, proof_strategy: ProofStrategy):
        self.proof_strategy = proof_strategy
        self.validation_report: Dict[str, Any] = {}
    
    def validate(self) -> Dict[str, Any]:
        """Run full validation."""
        validation = {
            'mechanism_type': self.proof_strategy.mechanism_candidate.mechanism_type.value,
            'cochain_level': self.proof_strategy.mechanism_candidate.cochain_level,
        }
        
        # Run strategy-specific validation
        strategy_validation = self.proof_strategy.validate_proof()
        validation.update(strategy_validation)
        
        # Check coverage
        coverage = self.proof_strategy.coverage
        validation['coverage_complete'] = all(coverage.values())
        
        if validation['coverage_complete']:
            validation['status'] = "VALID - Proof covers all requirements"
        else:
            missing = [k for k, v in coverage.items() if not v]
            validation['status'] = f"INCOMPLETE - Missing: {', '.join(missing)}"
        
        self.validation_report = validation
        return validation
    
    def validation_report_text(self) -> str:
        """Generate human-readable report."""
        lines = [
            "PROOF VALIDATION REPORT",
            "=" * 80,
            f"Mechanism Type: {self.validation_report.get('mechanism_type', 'N/A')}",
            f"Cochain Level: H^{self.validation_report.get('cochain_level', 'N/A')}",
            f"Status: {self.validation_report.get('status', 'N/A')}",
            "",
            self.proof_strategy.coverage_report(),
            "",
            f"Proof Type: {self.validation_report.get('proof_type', 'N/A')}",
            f"All Requirements Covered: {self.validation_report.get('all_covered', False)}",
        ]
        
        return "\n".join(lines)


