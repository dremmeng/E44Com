"""
Abstract base for all proof strategies. Each mechanism type has a specific
proof strategy appropriate to its structure.
"""


class ProofStrategy(ABC):
    """
    Base class for proof strategies.
    
    Attributes
    ----------
    mechanism_candidate : MechanismTheoremCandidate
        The theorem being proved.
    
    proof_outline : str
        High-level description of proof strategy.
    
    lemmas : list
        Key lemmas needed.
    
    coverage : Dict[str, bool]
        Whether proof covers each requirement:
        - pbw_degrees: all omitted degrees
        - t_levels: all cochain levels
        - weight_arms: all weight restrictions
        - non_occurrence: why no new cohomology outside core
        - generation: how descendants are generated
    
    validation_status : str
        "Outline", "In Progress", "Complete", "Peer-Reviewed"
    """
    
    def __init__(self, mechanism_candidate: MechanismTheoremCandidate):
        self.mechanism_candidate = mechanism_candidate
        self.proof_outline = ""
        self.lemmas: List[str] = []
        self.coverage: Dict[str, bool] = {
            'pbw_degrees': False,
            't_levels': False,
            'weight_arms': False,
            'non_occurrence': False,
            'generation': False,
        }
        self.validation_status = "Outline"
    
    @abstractmethod
    def construct_proof(self) -> str:
        """Construct the proof. Return proof text."""
        pass
    
    @abstractmethod
    def validate_proof(self) -> Dict[str, Any]:
        """Validate proof completeness. Return validation report."""
        pass
    
    def mark_coverage(self, requirement: str) -> None:
        """Mark that a requirement is covered by the proof."""
        if requirement in self.coverage:
            self.coverage[requirement] = True
    
    def coverage_report(self) -> str:
        """Report which requirements are covered."""
        lines = ["Proof Coverage:"]
        for req, covered in self.coverage.items():
            status = "✓" if covered else "✗"
            lines.append(f"  {status} {req}")
        return "\n".join(lines)


