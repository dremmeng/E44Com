"""
A formal statement of the conjectured mechanism.
"""


@dataclass
class MechanismTheoremCandidate:
    """
    A formal statement of the conjectured mechanism theorem.
    
    Attributes
    ----------
    mechanism_type : MechanismType
        Type of mechanism (acyclic tail, finite generation, periodicity, SS)
    
    cochain_level : int
        The cochain level k for which the theorem is stated.
    
    statement : str
        Precise mathematical statement of the conjecture.
    
    exact_labels : Dict[str, Any]
        Exact labels and thresholds used in the statement.
    
    evidence : Dict[str, Any]
        Computed sectors and data supporting the conjecture.
    
    gaps : List[str]
        Identified gaps or limitations.
    
    confidence : float
        Overall confidence in the conjecture (0-1).
    
    proof_sketch : str
        Sketch of how this would be proved (for Step 7).
    
    related_candidates : List[str]
        Other candidates considered.
    """
    mechanism_type: MechanismType
    cochain_level: int
    statement: str
    exact_labels: Dict[str, Any]
    evidence: Dict[str, Any]
    gaps: List[str]
    confidence: float
    proof_sketch: str
    related_candidates: List[str] = field(default_factory=list)
    
    def formalize(self) -> str:
        """Generate formal statement for publication."""
        lines = [
            "MECHANISM THEOREM CANDIDATE",
            "=" * 80,
            f"Type: {self.mechanism_type.value}",
            f"Cochain Level: H^{self.cochain_level}",
            f"Confidence: {self.confidence:.1%}",
            "",
            "STATEMENT:",
            self.statement,
            "",
            "EXACT LABELS AND THRESHOLDS:",
        ]
        
        for label, value in self.exact_labels.items():
            lines.append(f"  {label}: {value}")
        
        lines.extend([
            "",
            "EVIDENCE:",
            f"  Sectors Analyzed: {self.evidence.get('sectors_analyzed', 'N/A')}",
            f"  Pattern Confirmed: {self.evidence.get('pattern_confirmed', 'N/A')}",
        ])
        
        if self.gaps:
            lines.append("")
            lines.append("GAPS IN PROOF (to be addressed in Step 7):")
            for gap in self.gaps:
                lines.append(f"  - {gap}")
        
        lines.extend([
            "",
            "PROOF SKETCH (Step 7):",
            self.proof_sketch,
            "",
            "ALTERNATIVE CANDIDATES CONSIDERED:",
        ])
        
        for candidate in self.related_candidates:
            lines.append(f"  - {candidate}")
        
        return "\n".join(lines)


