"""
Analyzes cohomology data to detect patterns and formulate candidates.
"""


class MechanismTheoremAnalyzer:
    """
    Analyzes cohomology certificates to formulate mechanism candidates.
    
    Attributes
    ----------
    cohomology_certs : dict {SectorLabel -> CohomologyRankCertificate}
        Input cohomology data from Step 5.
    
    detected_candidates : list
        Candidates ranked by evidence strength.
    
    best_candidate : optional
        The highest-confidence candidate.
    
    analysis_metadata : dict
        Summary of analysis process.
    """
    
    def __init__(self, cohomology_certs: Dict[SectorLabel, CohomologyRankCertificate]):
        self.cohomology_certs = cohomology_certs
        self.detected_candidates: List[Any] = []
        self.best_candidate: Optional[Any] = None
        self.analysis_metadata: Dict[str, Any] = {}
    
    def detect_acyclic_tail(self, cochain_level: int) -> Optional[AcyclicTailCandidiate]:
        """
        Detect if H^k = 0 outside a finite region of sector labels.
        
        Parameters
        ----------
        cochain_level : int
            The cochain level k to analyze.
        
        Returns
        -------
        AcyclicTailCandidate or None
            If pattern detected, return candidate with confidence.
        """
        acyclic_regions = []
        nonzero_regions = []
        
        # Analyze all sectors
        for sector, cert in self.cohomology_certs.items():
            if not cert.is_valid():
                continue
            
            rank_k = cert.rank_by_level.get(cochain_level, 0)
            
            # Organize by sector parameters (n, weight, complex)
            region_key = (sector.n, sector.weight, sector.complex_id)
            
            if rank_k == 0:
                acyclic_regions.append((sector, cert.max_degree_computed))
            else:
                nonzero_regions.append((sector, cert.max_degree_computed, rank_k))
        
        # Estimate threshold and confidence
        if acyclic_regions and nonzero_regions:
            # Look for boundary between acyclic and nonzero regions
            max_nonzero_n = max(s.n for s, _ in nonzero_regions)
            min_acyclic_n = min(s.n for s, _ in acyclic_regions)
            
            if min_acyclic_n > max_nonzero_n:
                # Clean separation!
                threshold = {"n": max_nonzero_n}
                confidence = 0.8  # Good separation
                
                return AcyclicTailCandidiate(
                    cochain_level=cochain_level,
                    support_threshold=threshold,
                    acyclic_regions=acyclic_regions,
                    nonzero_regions=nonzero_regions,
                    threshold_confidence=confidence,
                    evidence_sectors=len(self.cohomology_certs),
                    proof_status="Conjectured",
                )
        
        return None
    
    def detect_finite_generation(self, cochain_level: int) -> Optional[FiniteGenerationCandidate]:
        """
        Detect if H^k is generated by finitely many HW classes.
        
        Parameters
        ----------
        cochain_level : int
            The cochain level k to analyze.
        
        Returns
        -------
        FiniteGenerationCandidate or None
            If pattern detected, return candidate.
        """
        generators = []
        total_dimension = 0
        
        # Analyze HW structure across all sectors
        hw_counts = defaultdict(int)
        
        for sector, cert in self.cohomology_certs.items():
            if not cert.is_valid():
                continue
            
            rank_k = cert.rank_by_level.get(cochain_level, 0)
            total_dimension += rank_k
            
            # Collect HW components from decomposition (if available)
            if cert.hw_decomposition_summary:
                for hw_comp, count in cert.hw_decomposition_summary.items():
                    hw_counts[hw_comp] += count
        
        # If we see repeated HW components, they might be generators
        repeated_hw = {hw: count for hw, count in hw_counts.items() if count >= 2}
        
        if repeated_hw:
            generators = [
                {"weight": hw, "dimension": 0, "character": ""}
                for hw in repeated_hw.keys()
            ]
            
            confidence = min(0.7, len(repeated_hw) / max(1, len(hw_counts)))
            
            return FiniteGenerationCandidate(
                cochain_level=cochain_level,
                generators=generators,
                generation_rule="Unknown (conjectured)",
                character_formula="TBD",
                evidence_sectors=len(self.cohomology_certs),
                generation_confidence=confidence,
                proof_status="Conjectured",
            )
        
        return None
    
    def detect_periodicity(self, cochain_level: int) -> Optional[PeriodicityCandidate]:
        """
        Detect if sector cohomology follows a shift/translation rule.
        
        Parameters
        ----------
        cochain_level : int
            The cochain level k to analyze.
        
        Returns
        -------
        PeriodicityCandidate or None
            If pattern detected, return candidate.
        """
        # Organize sectors by (n, weight)
        rank_by_invariants = defaultdict(list)
        
        for sector, cert in self.cohomology_certs.items():
            if not cert.is_valid():
                continue
            
            rank_k = cert.rank_by_level.get(cochain_level, 0)
            key = (sector.n, sector.weight)
            rank_by_invariants[key].append(rank_k)
        
        # Look for periodicity: do ranks repeat?
        rank_sequences = list(rank_by_invariants.values())
        
        if rank_sequences and all(len(seq) >= 2 for seq in rank_sequences):
            # Check if any sequence has a period
            for seq in rank_sequences:
                # Simple period detection
                if len(seq) >= 3:
                    # Check if first two elements repeat
                    if seq[0] == seq[2] or seq[1] == seq[3] if len(seq) > 3 else False:
                        return PeriodicityCandidate(
                            cochain_level=cochain_level,
                            shift_rule="Conjectured shift rule (needs analysis)",
                            period=2,
                            evidence_sectors=len(rank_by_invariants),
                            periodicity_confidence=0.5,
                            proof_status="Conjectured",
                        )
        
        return None
    
    def detect_spectral_sequence(self, cochain_level: int) -> Optional[SpectralSequenceCandidate]:
        """
        Detect if associated graded complex is exact outside finite set.
        
        Parameters
        ----------
        cochain_level : int
            The cochain level k to analyze.
        
        Returns
        -------
        SpectralSequenceCandidate or None
            If pattern detected, return candidate.
        """
        # Analyze exactness by PBW degree
        exactness_by_degree = defaultdict(bool)
        
        for sector, cert in self.cohomology_certs.items():
            if not cert.is_valid():
                continue
            
            # Check dimensions by degree
            if cochain_level in cert.dimensions_by_degree:
                dims = cert.dimensions_by_degree[cochain_level]
                # Simple heuristic: if dimension is 0, likely exact
                for d, dim in dims.items():
                    exactness_by_degree[d] = (dim == 0)
        
        # Look for threshold beyond which exactness holds
        exact_degrees = sorted([d for d, ex in exactness_by_degree.items() if ex])
        
        if exact_degrees and len(exact_degrees) >= 3:
            # Check if there's a threshold
            min_exact = min(exact_degrees)
            max_exact = max(exact_degrees)
            
            if max_exact - min_exact >= 2:  # Some gap
                return SpectralSequenceCandidate(
                    cochain_level=cochain_level,
                    filtration="by_pbw_degree",
                    vanishing_threshold={"degree": min_exact},
                    evidence_sectors=len(self.cohomology_certs),
                    exactness_confidence=0.6,
                    proof_status="Conjectured",
                )
        
        return None
    
    def analyze_all_candidates(self) -> List[Any]:
        """
        Analyze all cochain levels for all candidate types.
        
        Returns
        -------
        list
            All detected candidates, ranked by confidence.
        """
        all_candidates = []
        
        # Determine which cochain levels are present
        cochain_levels = set()
        for cert in self.cohomology_certs.values():
            cochain_levels.update(cert.rank_by_level.keys())
        
        # For each cochain level, detect all candidate types
        for k in sorted(cochain_levels):
            acyclic = self.detect_acyclic_tail(k)
            if acyclic:
                all_candidates.append((acyclic.threshold_confidence, acyclic))
            
            generation = self.detect_finite_generation(k)
            if generation:
                all_candidates.append((generation.generation_confidence, generation))
            
            periodicity = self.detect_periodicity(k)
            if periodicity:
                all_candidates.append((periodicity.periodicity_confidence, periodicity))
            
            spectral = self.detect_spectral_sequence(k)
            if spectral:
                all_candidates.append((spectral.exactness_confidence, spectral))
        
        # Sort by confidence (descending)
        all_candidates.sort(key=lambda x: x[0], reverse=True)
        self.detected_candidates = [c for _, c in all_candidates]
        
        if self.detected_candidates:
            self.best_candidate = self.detected_candidates[0]
        
        return self.detected_candidates
    
    def generate_analysis_report(self) -> str:
        """Generate a comprehensive analysis report."""
        lines = [
            "=" * 80,
            "MECHANISM THEOREM ANALYSIS REPORT",
            "=" * 80,
            f"\nCohomology Certificates Analyzed: {len(self.cohomology_certs)}",
            f"Candidates Detected: {len(self.detected_candidates)}",
        ]
        
        if self.best_candidate:
            lines.append(f"\n[BEST CANDIDATE]")
            lines.append(self.best_candidate.summary())
        
        if len(self.detected_candidates) > 1:
            lines.append(f"\n[OTHER CANDIDATES]")
            for candidate in self.detected_candidates[1:]:
                lines.append(candidate.summary())
        
        lines.extend([
            "",
            "=" * 80,
            "NEXT STEP: Step 7 will prove the selected mechanism.",
            "=" * 80,
        ])
        
        return "\n".join(lines)


