"""
Four types of mechanism candidates, each with precise definition and evidence.
"""


class MechanismType(Enum):
    """Possible mechanism types."""
    ACYCLIC_TAIL = "acyclic_tail"
    FINITE_GENERATION = "finite_generation"
    PERIODICITY_RECURRENCE = "periodicity_recurrence"
    SPECTRAL_SEQUENCE = "spectral_sequence"
    UNKNOWN = "unknown"


@dataclass
class AcyclicTailCandidiate:
    """
    Candidate: H^k(C_λ) = 0 outside a finite region of sector labels.
    
    Attributes
    ----------
    cochain_level : int
        The cochain level k for which we claim acyclic tail.
    
    support_threshold : Dict[str, int]
        Bounds on sector parameters: {parameter -> max_value}
        e.g., {"n": 5, "weight": (2,2,2)}
    
    acyclic_regions : list of (SectorLabel, PBW_degree)
        All computed (sector, degree) pairs with H^k = 0.
    
    nonzero_regions : list of (SectorLabel, PBW_degree, dimension)
        All computed pairs with H^k ≠ 0 (for reference).
    
    threshold_confidence : float
        Confidence that threshold is correct (0-1).
        Based on pattern coverage.
    
    evidence_sectors : int
        Number of sectors used in analysis.
    
    proof_status : str
        "Conjectured", "Partially Proved", "Proved"
    
    gaps : list
        Identified gaps or exceptions to the pattern.
    """
    cochain_level: int
    support_threshold: Dict[str, Any]
    acyclic_regions: List[Tuple[SectorLabel, int]]
    nonzero_regions: List[Tuple[SectorLabel, int, int]]
    threshold_confidence: float
    evidence_sectors: int
    proof_status: str
    gaps: List[str] = field(default_factory=list)
    
    def summary(self) -> str:
        """Return human-readable summary."""
        lines = [
            f"Acyclic Tail Candidate (H^{self.cochain_level})",
            f"  Support Threshold: {self.support_threshold}",
            f"  Confidence: {self.threshold_confidence:.1%}",
            f"  Evidence Sectors: {self.evidence_sectors}",
            f"  Acyclic Regions: {len(self.acyclic_regions)}",
            f"  Nonzero Regions: {len(self.nonzero_regions)}",
            f"  Proof Status: {self.proof_status}",
        ]
        if self.gaps:
            lines.append(f"  Gaps: {'; '.join(self.gaps[:3])}")
        return "\n".join(lines)


@dataclass
class FiniteGenerationCandidate:
    """
    Candidate: H^k is generated by finitely many highest/lowest-weight classes.
    
    Attributes
    ----------
    cochain_level : int
        The cochain level k.
    
    generators : list of dict
        Each generator: {"weight": λ, "dimension": dim, "character": ch}
    
    generation_rule : str
        How descendants are generated from generators.
        e.g., "tensor_with_exterior_algebra"
    
    character_formula : str
        Closed-form or recursive formula for ch(H^k).
    
    evidence_sectors : int
        Number of sectors confirming generation structure.
    
    generation_confidence : float
        Confidence in the generation mechanism (0-1).
    
    proof_status : str
        "Conjectured", "Partially Proved", "Proved"
    
    gaps : list
        Identified gaps or exceptions.
    """
    cochain_level: int
    generators: List[Dict[str, Any]]
    generation_rule: str
    character_formula: str
    evidence_sectors: int
    generation_confidence: float
    proof_status: str
    gaps: List[str] = field(default_factory=list)
    
    def summary(self) -> str:
        """Return human-readable summary."""
        lines = [
            f"Finite Generation Candidate (H^{self.cochain_level})",
            f"  Generators: {len(self.generators)}",
            f"  Generation Rule: {self.generation_rule}",
            f"  Confidence: {self.generation_confidence:.1%}",
            f"  Evidence Sectors: {self.evidence_sectors}",
            f"  Proof Status: {self.proof_status}",
            f"  Character Formula: {self.character_formula}",
        ]
